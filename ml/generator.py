SCENARIO_TYPES = [
    "NORMAL_BASELINE",
    "GRADUAL_GAS_BUILDUP",
    "SUDDEN_OUTBURST_SURGE",
    "DEGRADED_VENTILATION",
    "VENTILATION_RECOVERY",
    "MACHINE_ACTIVITY_SURGE",
    "SENSOR_ANOMALY",
]


@dataclass
class GeneratorConfig:
    seed: int = 42
    target_rows: int = 150000
    start_time: str = "2026-06-01 00:00:00"
    episode_duration_minutes: int = 720  # 12 hours per episode
    zones: Optional[List[Dict]] = None


class MineTelemetryGenerator:
    """
    Programmatic synthetic atmospheric telemetry generator for underground coal mines.
    Produces physical state transitions (dilution vs desorption, activity surges, barometric effects).
    """

    def __init__(self, config: Optional[GeneratorConfig] = None):
        self.config = config or GeneratorConfig()
        self.zones = self.config.zones or DEFAULT_ZONES
        self.rng = np.random.default_rng(self.config.seed)

    def generate_dataset(self) -> pd.DataFrame:
        """
        Generates the full multi-zone, multi-episode dataset meeting the target rows.
        """
        num_zones = len(self.zones)
        # Each episode covers episode_duration_minutes across 1 zone or parallel zones
        # To make clean disjoint episodes, we define episodes per zone:
        episodes_needed = int(np.ceil(self.config.target_rows / self.config.episode_duration_minutes))
        
        start_dt = datetime.strptime(self.config.start_time, "%Y-%m-%d %H:%M:%S")
        all_dfs = []
        rows_accumulated = 0
        episode_counter = 1

        while rows_accumulated < self.config.target_rows:
            # Pick zone round-robin or stochastic
            zone = self.zones[(episode_counter - 1) % num_zones]
            # Pick a scenario type weighted towards normal, but with rich anomalies
            scenario = self._select_scenario()
            
            # Episode start time advances systematically
            ep_start = start_dt + timedelta(minutes=(episode_counter - 1) * 360)
            
            ep_df = self._generate_episode(
                episode_id=f"EP-{episode_counter:04d}",
                zone=zone,
                scenario_type=scenario,
                start_time=ep_start,
                duration_minutes=self.config.episode_duration_minutes,
            )
            all_dfs.append(ep_df)
            rows_accumulated += len(ep_df)
            episode_counter += 1

        full_df = pd.concat(all_dfs, ignore_index=True)
        # Trim to target if slightly over
        if len(full_df) > self.config.target_rows:
            full_df = full_df.iloc[:self.config.target_rows].copy()
        
        # Sort chronologically by zone and timestamp
        full_df["timestamp"] = pd.to_datetime(full_df["timestamp"])
        full_df = full_df.sort_values(by=["timestamp", "zone_id"]).reset_index(drop=True)
        return full_df

    def _select_scenario(self) -> str:
        weights = [0.40, 0.16, 0.10, 0.12, 0.08, 0.10, 0.04]
        return self.rng.choice(SCENARIO_TYPES, p=weights)

    def _generate_episode(
        self,
        episode_id: str,
        zone: Dict,
        scenario_type: str,
        start_time: datetime,
        duration_minutes: int,
    ) -> pd.DataFrame:
        """
        Simulates minute-by-minute physical variables for a single episode in a single zone.
        """
        n = duration_minutes
        times = [start_time + timedelta(minutes=i) for i in range(n)]
        
        # Base zone characteristics
        base_airflow = zone["base_airflow"]
        base_ch4 = zone["base_ch4"]
        base_temp = zone["base_temp"]
        base_hum = zone["base_humidity"]
        base_press = zone["base_pressure"]
        gas_susc = zone["gas_susceptibility"]

        # 1. Machine activity: discrete state 0=idle, 1=low, 2=active, 3=peak cutting
        machine_activity = np.zeros(n, dtype=int)
        # Shift blocks of machine activity
        curr_act = self.rng.choice([0, 1, 2], p=[0.2, 0.3, 0.5])
        i = 0
        while i < n:
            block_len = self.rng.integers(30, 180)
            machine_activity[i : min(i + block_len, n)] = curr_act
            i += block_len
            curr_act = self.rng.choice([0, 1, 2, 3], p=[0.15, 0.25, 0.45, 0.15])

        # 2. Ventilation state: NORMAL, DEGRADED, BOOSTED, RESTRICTED
        vent_state = ["NORMAL"] * n
        airflow = np.zeros(n)
        methane = np.zeros(n)
        temp = np.zeros(n)
        humidity = np.zeros(n)
        pressure = np.zeros(n)

        # Baseline physical profiles
        ambient_press_drift = np.sin(np.linspace(0, 2 * np.pi, n)) * 0.3 + self.rng.normal(0, 0.05, n)
        pressure = base_press + ambient_press_drift
        
        # Airflow base noise
        airflow_series = base_airflow + self.rng.normal(0, 0.3, n)
        
        # Scenario adjustments
        if scenario_type == "NORMAL_BASELINE":
            # Normal steady operation with minor variations
            pass

        elif scenario_type == "GRADUAL_GAS_BUILDUP":
            # Slow steady increase in methane emission over several hours
            event_start = self.rng.integers(int(n * 0.2), int(n * 0.4))
            event_duration = self.rng.integers(int(n * 0.4), int(n * 0.6))
            end_idx = min(event_start + event_duration, n)
            buildup_ramp = np.linspace(0, 0.9 * gas_susc, end_idx - event_start)
            # Pressure drop exacerbates desorption
            pressure[event_start:end_idx] -= np.linspace(0, 0.6, end_idx - event_start)
            # Methane adds ramp
            gas_ramp_addon = np.zeros(n)
            gas_ramp_addon[event_start:end_idx] = buildup_ramp
            gas_ramp_addon[end_idx:] = buildup_ramp[-1] * np.exp(-np.linspace(0, 2, n - end_idx))

        elif scenario_type == "SUDDEN_OUTBURST_SURGE":
            # Sudden burst: e.g. gas pocket breach during cutting
            event_start = self.rng.integers(int(n * 0.3), int(n * 0.7))
            burst_len = self.rng.integers(15, 45)
            end_burst = min(event_start + burst_len, n)
            machine_activity[max(0, event_start - 20) : event_start] = 3
            gas_burst_addon = np.zeros(n)
            # Sharp rise in 5 mins, exponential decay
            peak = 1.3 * gas_susc + self.rng.uniform(0.2, 0.6)
            rise_len = min(6, end_burst - event_start)
            gas_burst_addon[event_start : event_start + rise_len] = np.linspace(0, peak, rise_len)
            decay_len = end_burst - (event_start + rise_len)
            if decay_len > 0:
                gas_burst_addon[event_start + rise_len : end_burst] = peak * np.exp(
                    -np.linspace(0, 2.5, decay_len)
                )

        elif scenario_type == "DEGRADED_VENTILATION":
            # Fan throttle / airway blockage
            event_start = self.rng.integers(int(n * 0.25), int(n * 0.55))
            event_duration = self.rng.integers(int(n * 0.3), int(n * 0.5))
            end_event = min(event_start + event_duration, n)
            # Airflow drops drastically
            airflow_drop_factor = self.rng.uniform(0.35, 0.55)
            airflow_series[event_start:end_event] *= airflow_drop_factor
            for idx in range(event_start, end_event):
                vent_state[idx] = "DEGRADED"

        elif scenario_type == "VENTILATION_RECOVERY":
            # Starts elevated, then booster fan triggers
            event_start = self.rng.integers(int(n * 0.2), int(n * 0.4))
            recovery_start = event_start + self.rng.integers(60, 150)
            end_event = min(recovery_start + 120, n)
            for idx in range(recovery_start, end_event):
                vent_state[idx] = "BOOSTED"
                airflow_series[idx] = base_airflow * 1.35 + self.rng.normal(0, 0.2)

        elif scenario_type == "MACHINE_ACTIVITY_SURGE":
            # Heavy continuous cutting
            event_start = self.rng.integers(int(n * 0.15), int(n * 0.45))
            event_duration = self.rng.integers(120, 240)
            end_event = min(event_start + event_duration, n)
            machine_activity[event_start:end_event] = 3

        # Simulate dynamic continuous differential equation for Methane Concentration:
        # d(CH4)/dt = Desorption(Activity, Pressure, Scenario) - Dilution(Airflow) * CH4 + Noise
        ch4_val = base_ch4 + self.rng.normal(0, 0.02)
        for t in range(n):
            af = max(2.0, airflow_series[t])
            act = machine_activity[t]
            pr = pressure[t]
            
            # Desorption rate influenced by machine cutting and barometric pressure drop
            # Lower barometric pressure -> higher gas emission (Boyle's law / Darcy flow in fractured coal)
            pr_effect = max(0.0, (101.5 - pr) * 0.08)
            act_effect = act * 0.05 * gas_susc
            
            # Scenario additive emission
            scenario_emission = 0.0
            if scenario_type == "GRADUAL_GAS_BUILDUP":
                scenario_emission = gas_ramp_addon[t] * 0.04
            elif scenario_type == "SUDDEN_OUTBURST_SURGE":
                scenario_emission = gas_burst_addon[t] * 0.12
            elif scenario_type == "DEGRADED_VENTILATION" and vent_state[t] == "DEGRADED":
                scenario_emission = 0.05 * gas_susc
            elif scenario_type == "MACHINE_ACTIVITY_SURGE" and act == 3:
                scenario_emission = 0.08 * gas_susc

            # Effective equilibrium level for current conditions
            ch4_target = (base_ch4 + act_effect + pr_effect + scenario_emission) * (base_airflow / af) ** 0.8
            
            if vent_state[t] == "BOOSTED":
                ch4_target *= 0.65

            # Inertial convergence + stochastic fluctuation
            alpha = 0.08  # time constant ~ 12-15 minutes response
            ch4_val += alpha * (ch4_target - ch4_val) + self.rng.normal(0, 0.012)
            
            # Keep within physical bounds
            ch4_val = float(np.clip(ch4_val, 0.02, 4.8))
            methane[t] = ch4_val

            # Temperature and humidity dynamics
            # Higher machine activity & airflow reduction slightly increases temp
            temp[t] = base_temp + act * 0.4 + (base_airflow / af - 1.0) * 0.8 + self.rng.normal(0, 0.1)
            humidity[t] = np.clip(base_hum + (temp[t] - base_temp) * 0.5 + self.rng.normal(0, 0.3), 40.0, 99.0)
            airflow[t] = np.round(af, 2)

        # Handle sensor anomaly scenario
        if scenario_type == "SENSOR_ANOMALY":
            anomaly_point = self.rng.integers(int(n * 0.3), int(n * 0.7))
            anomaly_kind = self.rng.choice(["SPIKE", "DROPOUT", "FLATLINE"])
            if anomaly_kind == "SPIKE":
                # Single-minute transient electrical noise spike
                methane[anomaly_point] = 4.2
            elif anomaly_kind == "DROPOUT":
                # Zero drop out for 3 minutes
                methane[anomaly_point : min(anomaly_point + 3, n)] = 0.0
            elif anomaly_kind == "FLATLINE":
                # Sensor freeze
                flat_val = methane[anomaly_point]
                methane[anomaly_point : min(anomaly_point + 15, n)] = flat_val

        df = pd.DataFrame(
            {
                "timestamp": [dt.strftime("%Y-%m-%d %H:%M:%S") for dt in times],
                "zone_id": zone["zone_id"],
                "episode_id": episode_id,
                "methane_pct": np.round(methane, 4),
                "airflow": np.round(airflow, 2),
                "temperature_c": np.round(temp, 2),
                "humidity_pct": np.round(humidity, 2),
                "pressure_kpa": np.round(pressure, 2),
                "machine_activity": machine_activity,
                "ventilation_state": vent_state,
                "scenario_type": scenario_type,
            }
        )
        return df


def generate_and_save_dataset(
    output_path: str = "data/generated/synthetic_mine_sensors_150k.csv",
    target_rows: int = 150000,
    seed: int = 42,
) -> pd.DataFrame:
    """Convenience function to generate and persist synthetic dataset."""
    import os
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    cfg = GeneratorConfig(target_rows=target_rows, seed=seed)
    gen = MineTelemetryGenerator(cfg)
    df = gen.generate_dataset()
    df.to_csv(output_path, index=False)
    return df


